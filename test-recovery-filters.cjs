const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const el={innerHTML:'',addEventListener(){}};
const context={console,setTimeout,clearTimeout,document:{querySelector:()=>el,querySelectorAll:()=>[],addEventListener(){}},window:{addEventListener(){}},navigator:{onLine:true},location:{search:'?qa=1',protocol:'http:'},localStorage:{getItem:()=>null}};
vm.runInNewContext(fs.readFileSync('app.js','utf8'),context);
const {matchesRecovery,filtered}=context.window.__trainingQA;
const {recoveryCard}=context.window.__trainingQA;
const daily={'2026-09-28':{sleep:62,soreness:0,feeling:2,hrv:45},'2026-09-27':{sleep:70,soreness:6},'2026-09-26':{sleep:''}};
const base={q:'',type:'',status:'incomplete',start:'',end:'',tags:[],tagMode:'all','body-sleep-op':'lt','body-sleep-value':'70'};
const rec=(id,date,status,rpe)=>({id,date,status,result:{rpe},type:'run',title:id,createdAt:date,snapshot:{name:'跑步',custom:[],exercises:[]},tags:[]});
const records=[rec('partial','2026-09-28','partial',8),rec('skip','2026-09-28','skip',''),rec('done','2026-09-28','done',3),rec('pending','2026-09-28','pending',''),rec('boundary','2026-09-27','skip',9),rec('blank','2026-09-26','skip',''),rec('absent','2026-09-25','skip','')];
const ids=(f)=>Array.from(filtered(records,f,daily),r=>r.id).sort();
assert.deepEqual(ids(base),['partial','skip']);
assert.equal(recoveryCard(records[0],daily,{}),'');
assert.ok(recoveryCard(records[0],daily,base).includes('睡眠分數：62'));
assert.ok(!recoveryCard(records[0],daily,base).includes('HRV'));
assert.ok(recoveryCard(records[6],daily,{...base,'body-sleep-op':'missing'}).includes('未填寫'));
assert.deepEqual(ids({...base,'body-sleep-op':'lte'}),['boundary','partial','skip']);
assert.deepEqual(ids({...base,'body-sleep-op':'missing'}),['absent','blank']);
assert.deepEqual(ids({...base,'body-rpe-op':'gte','body-rpe-value':'8'}),['partial']);
assert.deepEqual(ids({...base,'body-rpe-op':'missing'}),['skip']);
assert.deepEqual(ids({...base,start:'2026-09-29'}),[]);
assert.deepEqual(ids({...base,tags:['不存在']}),[]);
assert.ok(matchesRecovery(records[0],daily,{'body-soreness-op':'eq','body-soreness-value':'0'}));
assert.ok(!matchesRecovery(records[0],daily,{'body-soreness-op':'missing'}));
assert.ok(matchesRecovery(records[0],daily,{'body-feeling-op':'lte','body-feeling-value':'2','body-hrv-op':'gt','body-hrv-value':'40'}));
assert.ok(matchesRecovery(records[6],daily,{'body-sleep-op':'lt','body-sleep-value':''}),'Incomplete condition stays inactive');
daily['2026-09-28'].sleep=80;
assert.deepEqual(ids(base),[],'Updating daily data changes all same-date matches without copying');
console.log('PASS: combined status, daily date join, boundaries, zero vs missing, RPE, dates/tags, live daily edits.');
